// Bundles src/main.ts into dist/Code.js for Apps Script and copies the manifest.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist');
mkdirSync(out, { recursive: true });

const ENTRY_POINTS = ['doGet', 'doPost', 'onOpen', 'setup', 'showToken', 'remindDue', 'installReminders'];

const result = await build({
  entryPoints: [join(root, 'src', 'main.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'ProjectFlow',
  target: 'es2019',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  write: false,
  legalComments: 'none',
  minify: true,
  logLevel: 'warning',
});

// Apps Script finds triggers and menu handlers by global function name, so expose real function declarations.
const stubs = ENTRY_POINTS.map(n => `function ${n}(e) { return ProjectFlow.${n}(e); }`).join('\n');
const code = `// Generated by apps/sheets/scripts/build.mjs — edit the TypeScript sources, not this file.\n${result.outputFiles[0].text}\n${stubs}\n`;
writeFileSync(join(out, 'Code.js'), code);
copyFileSync(join(root, 'appsscript.json'), join(out, 'appsscript.json'));
// The reference data ships as an HTML file of the Apps Script project, which is not parsed as code on every request.
writeFileSync(join(out, 'seed.html'), JSON.stringify(JSON.parse(readFileSync(join(root, '..', 'api', 'seed', 'sttp2b.json'), 'utf8'))));
const kb = (f) => (statSync(join(out, f)).size / 1024).toFixed(0);
console.log(`dist/Code.js ${kb('Code.js')} kB + seed.html ${kb('seed.html')} kB + appsscript.json`);
